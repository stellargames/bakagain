"""Book Hand's glyphs, drawn as broad-nib pen strokes.

Each glyph is a list of strokes; a stroke is the path of the nib's centre, through points given as
(x, y) in design units: x in BOOK.FNT columns, y in its rows above the baseline (x-height 7,
ascenders and capitals 11, descenders 4). build.py sweeps a broad nib along each one.

ADVANCES are BOOK.FNT's glyph widths in columns: the only thing taken from the original, so every
line wraps and fills exactly as the original's. The letterforms are drawn here, not traced.
"""

# ---- shared parts -------------------------------------------------------------------------------
def entry(x, top=7):
    """The hairline lead-in a minuscule stem starts with."""
    return [(x - 1.1, top - 0.9), (x - 0.3, top), (x + 0.1, top - 0.8)]


def foot(x):
    """The stroke ends by turning right along the baseline."""
    return [(x + 0.1, 0.9), (x + 0.6, 0.15), (x + 1.4, 0.2)]


def stem(x, top=7, end_foot=True):
    return entry(x, top) + [(x + 0.1, top - 2)] + (foot(x) if end_foot else [(x + 0.1, 0)])


def arch(x0, x1, top=7, end_foot=True):
    s = [(x0, 4.6), (x0 + 1.2, 6.5), (x0 + 2.6, top), (x1 - 0.2, 6.1), (x1, 4.5)]
    return s + (foot(x1 - 0.1) if end_foot else [(x1, 0.9), (x1, 0)])


def ascender(x, top=11):
    """A minuscule ascender with its flag."""
    return [(x - 1.2, top - 1.0), (x - 0.3, top), (x + 0.1, top - 0.9), (x + 0.1, top - 3)]


def capstem(x, top=11):
    """A capital's stem with the same flag."""
    return [(x - 1.4, top - 0.6), (x - 0.4, top), (x, top - 0.8), (x, top - 3)]


def mirror(strokes, adv, ink_right=1.6):
    """Left-right mirror inside the advance, keeping the reference's right-hand gap."""
    w = adv - ink_right
    return [[(w - x, y) for x, y in s] for s in strokes]


def scaled(strokes, sx=1.0, sy=1.0, dx=0.0, dy=0.0):
    return [[(x * sx + dx, y * sy + dy) for x, y in s] for s in strokes]


def ring(cx, cy, rx, ry, start_deg=100, n=10):
    import math
    pts = [(cx + rx * math.cos(math.radians(start_deg + 360 * k / n)),
            cy + ry * math.sin(math.radians(start_deg + 360 * k / n))) for k in range(n + 1)]
    return pts + [pts[1]]   # overlap the join so the nib closes the loop


